const GENRE_REASONS = new Set(['genres', 'genre', 'popular_genre']);

export type Translator = ReturnType<typeof makeT>;

export function makeT(lang: Lang) {
  const messages = MESSAGES[lang];
  const t = (key: MessageKey, vars: Record<string, string | number> = {}) =>
    messages[key].replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
  const genre = (name: string) => (lang === 'pt-BR' ? (GENRES_PT[name] ?? name) : name);
  const status = (value: string | null) =>
    value ? (lang === 'pt-BR' ? (STATUS_PT[value] ?? value) : value) : '';
  /** Motivo estruturado da API (`reason_key` + `reason_args`) no idioma atual. */
  const reason = (r: {
    reason_key?: string | null;
    reason_args?: string[];
    reason?: string | null;
  }) => {
    if (!r.reason_key) return r.reason ?? null;
    const key = `reason.${r.reason_key}` as MessageKey;
    if (!(key in messages)) return r.reason ?? null;
    const args = (r.reason_args ?? []).map(a => (GENRE_REASONS.has(r.reason_key!) ? genre(a) : a));
    return messages[key].replace(/\{(\d+)\}/g, (_, i) => args[Number(i)] ?? '');
  };
  const number = (n: number) => n.toLocaleString(lang);
  const date = (iso: string) => new Date(iso).toLocaleDateString(lang);
  return { lang, t, genre, status, reason, number, date };
}

export function useT() {
  const lang = useLang();
  return useMemo(() => makeT(lang), [lang]);
}
